from kos.sdk import App

TITLE = 'Tips'
LINES = ['', '  This app is a screen only. It does not do its job yet, and it does', '  not pretend to.', '', '  For: Short lessons on using the device.', '', '  Needs system state (processes, disks, logs, drivers, updates). No OS', '  service reads these for an app yet.', '', '  Instead, in KOS: `kos help`.', '', '  Ships on: iPhone (iOS), Mac (macOS), Windows 11, Apple Vision Pro.']


def main():
    app = App()
    top = 0
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            if k == "escape":
                app.exit(0)
                return
            if k == "down" and top < len(LINES) - 1:
                top += 1
            elif k == "up" and top > 0:
                top -= 1
        if ev["cmd"] != "pointer":
            h = app.height if isinstance(app.height, int) and app.height > 8 else 24
            app.screen(TITLE, LINES[top:top + h - 4], status="up/down scroll   Esc leave")
