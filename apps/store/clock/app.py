"""store.clock - Clock. UTC time and date, a world clock in whole and half-hour offsets, and a stopwatch.

Generated by suite/store_gen.py from suite/store_data.py; change those, not this file."""

import time

from kos.sdk import App

TITLE = "Clock"
ZONES = (("UTC", 0), ("Honolulu", -600), ("Los Angeles", -480), ("New York", -300), ("Sao Paulo", -180),
         ("London", 0), ("Berlin", 60), ("Cairo", 120), ("Moscow", 180), ("Dubai", 240), ("Delhi", 330),
         ("Dhaka", 360), ("Bangkok", 420), ("Beijing", 480), ("Tokyo", 540), ("Sydney", 600),
         ("Auckland", 720))
DAYS = ("Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat")

def civil(days):
    z = days + 719468
    era = z // 146097
    doe = z - era * 146097
    yoe = (doe - doe // 1460 + doe // 36524 - doe // 146096) // 365
    doy = doe - (365 * yoe + yoe // 4 - yoe // 100)
    mp = (5 * doy + 2) // 153
    d = doy - (153 * mp + 2) // 5 + 1
    m = mp + 3 if mp < 10 else mp - 9
    return yoe + era * 400 + (1 if m <= 2 else 0), m, d


def days_from_civil(y, m, d):
    y = y - (1 if m <= 2 else 0)
    era = y // 400
    yoe = y - era * 400
    doy = (153 * (m + (-3 if m > 2 else 9)) + 2) // 5 + d - 1
    doe = yoe * 365 + yoe // 4 - yoe // 100 + doy
    return era * 146097 + doe - 719468


def now_seconds():
    return time.time_ns() // 1000000000


def stamp(seconds, offset_minutes):
    t = seconds + offset_minutes * 60
    days, rest = divmod(t, 86400)
    y, m, d = civil(days)
    return f"{DAYS[(days + 4) % 7]} {y:04d}-{m:02d}-{d:02d} {rest // 3600:02d}:{rest % 3600 // 60:02d}"


def elapsed(ns):
    ms = ns // 1000000
    return f"{ms // 3600000}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d}.{ms % 1000:03d}"


def lines(state):
    now = now_seconds()
    out = ["", "  World clock (standard time: no daylight saving)", ""]
    out += [f"  {n:<12} {stamp(now, o)}" for n, o in ZONES]
    run = state["start"] is not None
    ns = (time.time_ns() - state["start"]) if run else state["total"]
    out += ["", f"  Stopwatch  {elapsed(ns)}  {'running (shows the time at your last key)' if run else 'stopped'}",
            "", "  s start/stop   r reset   Esc leave"]
    return out


def main():
    app = App()
    state = {"start": None, "total": 0}
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            if k == "escape":
                app.exit(0)
                return
            if k == "s":
                if state["start"] is None:
                    state["start"] = time.time_ns() - state["total"]
                else:
                    state["total"] = time.time_ns() - state["start"]
                    state["start"] = None
            elif k == "r":
                state.update(start=None, total=0)
        if ev["cmd"] != "pointer":
            app.screen(TITLE, lines(state), status="s: start/stop")
