from kos.sdk import App

TITLE = 'Measure'
LINES = ['', '  This app is a screen only. It does not do its job yet, and it does', '  not pretend to.', '', '  For: Measure real objects with the camera and motion sensors.', '', '  Needs a camera. Apps never open devices; the OS would have to read', '  one and hand frames over, and no command does that yet.', '', '  Instead, in KOS: `unit-converter` converts units exactly, but does', '  not measure anything.', '', '  Ships on: iPhone (iOS).']


def main():
    app = App()
    top = 0
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            if k == "escape":
                app.exit(0)
                return
            if k == "down" and top < len(LINES) - 1:
                top += 1
            elif k == "up" and top > 0:
                top -= 1
        if ev["cmd"] != "pointer":
            h = app.height if isinstance(app.height, int) and app.height > 8 else 24
            app.screen(TITLE, LINES[top:top + h - 4], status="up/down scroll   Esc leave")
