from kos.sdk import App

TITLE = 'Camera'
LINES = ['', '  This app is a screen only. It does not do its job yet, and it does', '  not pretend to.', '', '  For: Take photos and video (Camera, Photo Booth, Photo and Video', '  Capture are one function).', '', '  Needs a camera. Apps never open devices; the OS would have to read', '  one and hand frames over, and no command does that yet.', '', '  Ships on: Android phone, iPhone (iOS), Mac (macOS), Windows 11,', '  Linux desktop, Apple Vision Pro, Google Glass (historical), iGlasses', '  (proposed concept, not a real product).']


def main():
    app = App()
    top = 0
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            if k == "escape":
                app.exit(0)
                return
            if k == "down" and top < len(LINES) - 1:
                top += 1
            elif k == "up" and top > 0:
                top -= 1
        if ev["cmd"] != "pointer":
            h = app.height if isinstance(app.height, int) and app.height > 8 else 24
            app.screen(TITLE, LINES[top:top + h - 4], status="up/down scroll   Esc leave")
