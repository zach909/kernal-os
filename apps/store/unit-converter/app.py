"""store.unit-converter - Unit Converter. Converts length, mass and temperature exactly, as fractions.

Generated by suite/store_gen.py from suite/store_data.py; change those, not this file."""

from math import gcd

from kos.sdk import App

TITLE = "Unit Converter"
# every unit as a whole number of a tiny base unit, so conversions stay exact
FAMILIES = (
    ("length", (("mm", 10), ("cm", 100), ("m", 10000), ("km", 10000000), ("in", 254), ("ft", 3048),
                ("yd", 9144), ("mi", 16093440))),
    ("mass", (("mg", 1000000), ("g", 1000000000), ("kg", 1000000000000), ("oz", 28349523125),
              ("lb", 453592370000))),
    ("temperature", (("C", 0), ("F", 0), ("K", 0))),
)


def norm(n, d):
    g = gcd(n, d)
    n, d = n // g, d // g
    return (-n, -d) if d < 0 else (n, d)


def show(r):
    return str(r[0]) if r[1] == 1 else f"{r[0]}/{r[1]}"


def parse(text):
    """'-3', '7/2' -> (n, d) or None."""
    a, _, b = text.partition("/")
    sign = -1 if a.startswith("-") else 1
    a = a.lstrip("-")
    if not a.isdigit() or not a.isascii() or (_ and (not b.isdigit() or not b.isascii() or int(b) == 0)):
        return None
    return norm(sign * int(a), int(b) if _ else 1)


def to_kelvin(u, v):
    n, d = v
    if u == "C":
        return norm(n * 100 + 27315 * d, d * 100)
    if u == "F":
        return norm((n * 100 + 45967 * d) * 5, d * 900)
    return v


def from_kelvin(u, v):
    n, d = v
    if u == "C":
        return norm(n * 100 - 27315 * d, d * 100)
    if u == "F":
        return norm(n * 900 - 45967 * 5 * d, d * 500)
    return v


def convert(fam, a, b, v):
    units = dict(FAMILIES[fam][1])
    if FAMILIES[fam][0] == "temperature":
        return from_kelvin(b, to_kelvin(a, v))
    return norm(v[0] * units[a], v[1] * units[b])


def lines(state):
    fam = FAMILIES[state["fam"]]
    names = [u for u, _ in fam[1]]
    a, b = names[state["a"] % len(names)], names[state["b"] % len(names)]
    v = parse(state["text"])
    out = ["", f"  {fam[0]}   (tab: next family)", "",
           f"  from {a}   (left/right)", f"  to   {b}   (up/down)", "", "  value  " + state["text"] + "_", ""]
    if v is None:
        out.append("  type a whole number or a fraction like -7/2")
    else:
        r = convert(state["fam"], a, b, v)
        out.append(f"  {show(v)} {a} = {show(r)} {b}   (exact: a fraction, never a decimal)")
    return out + ["", "  Esc leaves"]


def main():
    app = App()
    state = {"fam": 0, "a": 0, "b": 1, "text": "1"}
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            if k == "escape":
                app.exit(0)
                return
            if k == "tab":
                state.update(fam=(state["fam"] + 1) % len(FAMILIES), a=0, b=1)
            elif k == "left":
                state["a"] -= 1
            elif k == "right":
                state["a"] += 1
            elif k == "up":
                state["b"] -= 1
            elif k == "down":
                state["b"] += 1
            elif k == "backspace":
                state["text"] = state["text"][:-1]
            elif len(k) == 1 and k in "0123456789-/" and len(state["text"]) < 30:
                state["text"] += k
        if ev["cmd"] != "pointer":
            app.screen(TITLE, lines(state), status="exact fractions")
