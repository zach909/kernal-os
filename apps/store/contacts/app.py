"""store.contacts - Contacts. Name, phone and email records kept in the app's own storage.

Generated by suite/store_gen.py from suite/store_data.py; change those, not this file."""

import json

from kos.sdk import App

TITLE = "Contacts"
PREFIX = "c"
FIELDS = ("name", "phone", "email")
LIMIT = {"name": 40, "phone": 20, "email": 60}
PHONE_OK = "0123456789+-() "

def clean(s, n=200):
    return "".join(c if c.isprintable() else "?" for c in str(s))[:n]


def rows(app):
    h = app.height if isinstance(app.height, int) and app.height > 8 else 24
    return h - 6

MAX_ITEMS = 200


def next_key(existing):
    used = set(existing)
    for n in range(1, MAX_ITEMS + 1):
        if f"{PREFIX}-{n:04d}" not in used:
            return f"{PREFIX}-{n:04d}"
    return None


def my_keys(app):
    return sorted(k for k in app.vault_keys() if k.startswith(PREFIX + "-"))[:MAX_ITEMS]


def wrap(text, width=66, most=6):
    out = []
    for para in text.split("\n"):
        out += [para[i:i + width] for i in range(0, max(1, len(para)), width)]
    return out[:most]


def load(app):
    items = []
    for k in my_keys(app):
        try:
            v = json.loads(app.vault_get(k) or "")
        except ValueError:
            continue
        if isinstance(v, dict):
            items.append((k, {f: clean(v.get(f, ""), LIMIT[f]) for f in FIELDS}))
    return sorted(items, key=lambda i: i[1]["name"].lower())


def problem(rec):
    if not rec["name"].strip():
        return "give the contact a name"
    if rec["email"] and ("@" not in rec["email"] or " " in rec["email"]):
        return "that email has no @ or has a space"
    return ""


def lines(state, items, h):
    if state["mode"] == "edit":
        out = ["", "  New contact", ""]
        for i, f in enumerate(FIELDS):
            out.append(("  > " if i == state["field"] else "    ") + f"{f:<6} " + state["rec"][f] + ("_" if i == state["field"] else ""))
        return out + ["", "  tab next field   enter saves   Esc cancels"] + (["  " + state["note"]] if state["note"] else [])
    out = [""]
    if not items:
        out.append("  No contacts yet. Press n to add one.")
    top = max(0, min(state["sel"] - h // 2, len(items) - h))
    for i in range(top, min(len(items), top + h)):
        out.append(("  > " if i == state["sel"] else "    ") + items[i][1]["name"])
    if items:
        r = items[state["sel"]][1]
        out += ["", "  phone  " + (r["phone"] or "-"), "  email  " + (r["email"] or "-")]
    out += ["", "  up/down choose   n new   d delete   Esc leave"]
    if state["note"]:
        out.append("  " + state["note"])
    return out


def main():
    app = App()
    state = {"mode": "list", "sel": 0, "field": 0, "rec": {f: "" for f in FIELDS}, "note": ""}
    items = load(app)
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            state["note"] = ""
            if state["mode"] == "edit":
                f = FIELDS[state["field"]]
                if k == "escape":
                    state["mode"] = "list"
                elif k == "tab":
                    state["field"] = (state["field"] + 1) % len(FIELDS)
                elif k == "enter":
                    state["note"] = problem(state["rec"])
                    key = next_key([i[0] for i in items])
                    if not state["note"] and key is None:
                        state["note"] = "full: delete one first"
                    if not state["note"]:
                        if app.vault_put(key, json.dumps(state["rec"], sort_keys=True)):
                            items, state["mode"] = load(app), "list"
                            state["rec"] = {x: "" for x in FIELDS}
                        else:
                            state["note"] = "not saved: " + (app.vault_error or "refused")
                elif k == "backspace":
                    state["rec"][f] = state["rec"][f][:-1]
                elif len(k) == 1 and k.isprintable() and len(state["rec"][f]) < LIMIT[f] and (f != "phone" or k in PHONE_OK):
                    state["rec"][f] += k
            elif k == "escape":
                app.exit(0)
                return
            elif k == "up" and state["sel"] > 0:
                state["sel"] -= 1
            elif k == "down" and state["sel"] < len(items) - 1:
                state["sel"] += 1
            elif k == "n":
                state.update(mode="edit", field=0)
            elif k == "d" and items:
                if app.vault_delete(items[state["sel"]][0]):
                    items = load(app)
                    state["sel"] = max(0, min(state["sel"], len(items) - 1))
                else:
                    state["note"] = "not deleted: " + (app.vault_error or "refused")
        if ev["cmd"] != "pointer":
            app.screen(TITLE, lines(state, items, rows(app) - 6), status="n: new")
