"""store.reminders - Reminders. A checklist: add items, tick them off, delete them.

Generated by suite/store_gen.py from suite/store_data.py; change those, not this file."""

from kos.sdk import App

TITLE = "Reminders"
PREFIX = "r"
LIMIT = 100

def clean(s, n=200):
    return "".join(c if c.isprintable() else "?" for c in str(s))[:n]


def rows(app):
    h = app.height if isinstance(app.height, int) and app.height > 8 else 24
    return h - 6

MAX_ITEMS = 200


def next_key(existing):
    used = set(existing)
    for n in range(1, MAX_ITEMS + 1):
        if f"{PREFIX}-{n:04d}" not in used:
            return f"{PREFIX}-{n:04d}"
    return None


def my_keys(app):
    return sorted(k for k in app.vault_keys() if k.startswith(PREFIX + "-"))[:MAX_ITEMS]


def wrap(text, width=66, most=6):
    out = []
    for para in text.split("\n"):
        out += [para[i:i + width] for i in range(0, max(1, len(para)), width)]
    return out[:most]


def load(app):
    items = []
    for k in my_keys(app):
        v = app.vault_get(k)
        if isinstance(v, str) and v[:2] in ("0 ", "1 "):
            items.append((k, v[0] == "1", clean(v[2:], LIMIT)))
    return items


def lines(state, items, h):
    if state["mode"] == "edit":
        return ["", "  New reminder", "", "  " + state["text"] + "_", "", "  enter saves   Esc cancels"] + (["  " + state["note"]] if state["note"] else [])
    out = [""]
    if not items:
        out.append("  Nothing to remember. Press n to add one.")
    top = max(0, min(state["sel"] - h // 2, len(items) - h))
    for i in range(top, min(len(items), top + h)):
        out.append(("  > " if i == state["sel"] else "    ") + ("[x] " if items[i][1] else "[ ] ") + items[i][2])
    out += ["", "  up/down choose   space ticks   n new   d delete   Esc leave"]
    if state["note"]:
        out.append("  " + state["note"])
    return out


def main():
    app = App()
    state = {"mode": "list", "sel": 0, "text": "", "note": ""}
    items = load(app)
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            state["note"] = ""
            if state["mode"] == "edit":
                if k == "escape":
                    state["mode"] = "list"
                elif k == "enter" and state["text"].strip():
                    key = next_key([i[0] for i in items])
                    if key is None:
                        state["note"] = "full: delete one first"
                    elif app.vault_put(key, "0 " + state["text"].strip()):
                        items, state["mode"], state["text"] = load(app), "list", ""
                        state["sel"] = max(0, len(items) - 1)
                    else:
                        state["note"] = "not saved: " + (app.vault_error or "refused")
                elif k == "backspace":
                    state["text"] = state["text"][:-1]
                elif len(k) == 1 and k.isprintable() and len(state["text"]) < LIMIT:
                    state["text"] += k
            elif k == "escape":
                app.exit(0)
                return
            elif k == "up" and state["sel"] > 0:
                state["sel"] -= 1
            elif k == "down" and state["sel"] < len(items) - 1:
                state["sel"] += 1
            elif k == "n":
                state["mode"] = "edit"
            elif k in (" ", "space") and items:
                key, done, text = items[state["sel"]]
                if not app.vault_put(key, ("0 " if done else "1 ") + text):
                    state["note"] = "not saved: " + (app.vault_error or "refused")
                items = load(app)
            elif k == "d" and items:
                if app.vault_delete(items[state["sel"]][0]):
                    items = load(app)
                    state["sel"] = max(0, min(state["sel"], len(items) - 1))
                else:
                    state["note"] = "not deleted: " + (app.vault_error or "refused")
        if ev["cmd"] != "pointer":
            app.screen(TITLE, lines(state, items, rows(app) - 4), status="n: new")
