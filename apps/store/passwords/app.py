"""store.passwords - Passwords. Keeps name/secret pairs in the OS's own passwords store (the 'passwords' permission). Secrets are hidden until you press enter.

Generated by suite/store_gen.py from suite/store_data.py; change those, not this file."""

import re

from kos.sdk import App

TITLE = "Passwords"
STORE = "passwords"
NAME_RE = re.compile("^[a-z0-9][a-z0-9._-]{0,39}$")
NAME_OK = "abcdefghijklmnopqrstuvwxyz0123456789._-"
LIMIT = 200
MAX_ITEMS = 200

def clean(s, n=200):
    return "".join(c if c.isprintable() else "?" for c in str(s))[:n]


def rows(app):
    h = app.height if isinstance(app.height, int) and app.height > 8 else 24
    return h - 6


def lines(state, keys, h):
    if state["mode"] == "edit":
        f = state["field"]
        shown = state["secret"].__len__() * "*"
        return ["", "  New password", "",
                ("  > " if f == 0 else "    ") + "name    " + state["name"] + ("_" if f == 0 else ""),
                ("  > " if f == 1 else "    ") + "secret  " + shown + ("_" if f == 1 else ""), "",
                "  name: lowercase letters, digits . _ -   tab next field   enter saves   Esc cancels"] + (["  " + state["note"]] if state["note"] else [])
    out = [""]
    if not keys:
        out.append("  Nothing saved yet. Press n to add one.")
    top = max(0, min(state["sel"] - h // 2, len(keys) - h))
    for i in range(top, min(len(keys), top + h)):
        out.append(("  > " if i == state["sel"] else "    ") + keys[i])
    if keys:
        out += ["", "  secret  " + (state["shown"] if state["reveal"] else "(hidden: press enter)")]
    out += ["", "  up/down choose   enter shows   n new   d delete   Esc leave"]
    if state["note"]:
        out.append("  " + state["note"])
    return out


def main():
    app = App()
    state = {"mode": "list", "sel": 0, "field": 0, "name": "", "secret": "", "reveal": False, "shown": "", "note": ""}
    keys = sorted(app.secret_keys(STORE))[:MAX_ITEMS]
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            state["note"] = ""
            if state["mode"] == "edit":
                if k == "escape":
                    state.update(mode="list", name="", secret="")
                elif k == "tab":
                    state["field"] = 1 - state["field"]
                elif k == "enter":
                    if not NAME_RE.match(state["name"]) or not state["secret"]:
                        state["note"] = "needs a valid name and a secret"
                    elif len(keys) >= MAX_ITEMS:
                        state["note"] = "full: delete one first"
                    elif app.secret_put(STORE, state["name"], state["secret"]):
                        keys = sorted(app.secret_keys(STORE))[:MAX_ITEMS]
                        state.update(mode="list", name="", secret="", sel=0)
                    else:
                        state["note"] = "not saved: " + (app.vault_error or "refused")
                elif k == "backspace":
                    f = "name" if state["field"] == 0 else "secret"
                    state[f] = state[f][:-1]
                elif len(k) == 1 and k.isprintable():
                    if state["field"] == 0 and k in NAME_OK and len(state["name"]) < 40:
                        state["name"] += k
                    elif state["field"] == 1 and len(state["secret"]) < LIMIT:
                        state["secret"] += k
            else:
                reveal = False
                if k == "escape":
                    app.exit(0)
                    return
                if k == "up" and state["sel"] > 0:
                    state["sel"] -= 1
                elif k == "down" and state["sel"] < len(keys) - 1:
                    state["sel"] += 1
                elif k == "n":
                    state.update(mode="edit", field=0)
                elif k == "enter" and keys:
                    v = app.secret_get(STORE, keys[state["sel"]])
                    state["shown"], reveal = clean(v if v is not None else "(refused)"), True
                elif k == "d" and keys:
                    if app.secret_delete(STORE, keys[state["sel"]]):
                        keys = sorted(app.secret_keys(STORE))[:MAX_ITEMS]
                        state["sel"] = max(0, min(state["sel"], len(keys) - 1))
                    else:
                        state["note"] = "not deleted: " + (app.vault_error or "refused")
                state["reveal"] = reveal
        if ev["cmd"] != "pointer":
            app.screen(TITLE, lines(state, keys, rows(app) - 6), status="enter: show")
