from kos.sdk import App

TITLE = 'Feedback'
LINES = ['', '  This app is a screen only. It does not do its job yet, and it does', '  not pretend to.', '', '  For: Send feedback to the maker (Feedback Hub).', '', '  Needs network access. Every connection is blocked by default; this', '  app would need a manifest permission and a firewall rule for one', '  host, port and protocol, plus a service to talk to.', '', '  Ships on: Windows 11.']


def main():
    app = App()
    top = 0
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            if k == "escape":
                app.exit(0)
                return
            if k == "down" and top < len(LINES) - 1:
                top += 1
            elif k == "up" and top > 0:
                top -= 1
        if ev["cmd"] != "pointer":
            h = app.height if isinstance(app.height, int) and app.height > 8 else 24
            app.screen(TITLE, LINES[top:top + h - 4], status="up/down scroll   Esc leave")
