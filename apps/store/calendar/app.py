"""store.calendar - Calendar. A month grid for any year, today marked, with left/right for months and up/down for years.

Generated by suite/store_gen.py from suite/store_data.py; change those, not this file."""

import time

from kos.sdk import App

TITLE = "Calendar"
MONTHS = ("January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
          "November", "December")

def civil(days):
    z = days + 719468
    era = z // 146097
    doe = z - era * 146097
    yoe = (doe - doe // 1460 + doe // 36524 - doe // 146096) // 365
    doy = doe - (365 * yoe + yoe // 4 - yoe // 100)
    mp = (5 * doy + 2) // 153
    d = doy - (153 * mp + 2) // 5 + 1
    m = mp + 3 if mp < 10 else mp - 9
    return yoe + era * 400 + (1 if m <= 2 else 0), m, d


def days_from_civil(y, m, d):
    y = y - (1 if m <= 2 else 0)
    era = y // 400
    yoe = y - era * 400
    doy = (153 * (m + (-3 if m > 2 else 9)) + 2) // 5 + d - 1
    doe = yoe * 365 + yoe // 4 - yoe // 100 + doy
    return era * 146097 + doe - 719468


def now_seconds():
    return time.time_ns() // 1000000000


def month_days(y, m):
    if m == 2:
        return 29 if (y % 4 == 0 and y % 100 != 0) or y % 400 == 0 else 28
    return 30 if m in (4, 6, 9, 11) else 31


def grid(y, m, today):
    first = (days_from_civil(y, m, 1) + 4) % 7
    cells = [""] * first + [str(d) for d in range(1, month_days(y, m) + 1)]
    out = ["  Su  Mo  Tu  We  Th  Fr  Sa"]
    for i in range(0, len(cells), 7):
        row = ""
        for c in cells[i:i + 7]:
            mark = f"[{c}]" if c and (y, m, int(c)) == today else c
            row += f"{mark:>4}"
        out.append(" " + row)
    return out


def main():
    app = App()
    today = civil(now_seconds() // 86400)
    ym = [today[0], today[1]]
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            if k == "escape":
                app.exit(0)
                return
            if k == "right":
                ym[0], ym[1] = (ym[0] + 1, 1) if ym[1] == 12 else (ym[0], ym[1] + 1)
            elif k == "left":
                ym[0], ym[1] = (ym[0] - 1, 12) if ym[1] == 1 else (ym[0], ym[1] - 1)
            elif k == "down" and ym[0] < 9998:
                ym[0] += 1
            elif k == "up" and ym[0] > 2:
                ym[0] -= 1
            elif k == "t":
                ym[0], ym[1] = today[0], today[1]
            ym[0] = max(1, min(9999, ym[0]))
        if ev["cmd"] != "pointer":
            body = ["", f"  {MONTHS[ym[1] - 1]} {ym[0]}", ""] + grid(ym[0], ym[1], today)
            body += ["", f"  Today (UTC): {today[0]:04d}-{today[1]:02d}-{today[2]:02d}   [ ] marks it",
                     "  left/right month   up/down year   t today   Esc leave"]
            app.screen(TITLE, body, status="no events: dates only")
