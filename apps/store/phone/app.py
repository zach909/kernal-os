from kos.sdk import App

TITLE = 'Phone'
LINES = ['', '  This app is a screen only. It does not do its job yet, and it does', '  not pretend to.', '', '  For: Place and answer calls.', '', '  Needs radio hardware (Wi-Fi, Bluetooth, cellular). Only the OS may', '  touch hardware and it exposes no such command to apps yet.', '', '  Needs a modem and audio.', '', '  Ships on: Android phone, iPhone (iOS), Windows 11, Google Glass', '  (historical), iGlasses (proposed concept, not a real product).']


def main():
    app = App()
    top = 0
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            if k == "escape":
                app.exit(0)
                return
            if k == "down" and top < len(LINES) - 1:
                top += 1
            elif k == "up" and top > 0:
                top -= 1
        if ev["cmd"] != "pointer":
            h = app.height if isinstance(app.height, int) and app.height > 8 else 24
            app.screen(TITLE, LINES[top:top + h - 4], status="up/down scroll   Esc leave")
