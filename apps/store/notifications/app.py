from kos.sdk import App

TITLE = 'Notifications'
LINES = ['', '  This app is a screen only. It does not do its job yet, and it does', '  not pretend to.', '', '  For: Show alerts from apps.', '', '  Needs system state (processes, disks, logs, drivers, updates). No OS', '  service reads these for an app yet.', '', '  Apps never call each other, so a notification centre needs its own', '  design.', '', '  Ships on: Google Glass (historical), iGlasses (proposed concept, not', '  a real product).']


def main():
    app = App()
    top = 0
    for ev in app.events():
        if ev["cmd"] == "key":
            k = ev["key"]
            if k == "escape":
                app.exit(0)
                return
            if k == "down" and top < len(LINES) - 1:
                top += 1
            elif k == "up" and top > 0:
                top -= 1
        if ev["cmd"] != "pointer":
            h = app.height if isinstance(app.height, int) and app.height > 8 else 24
            app.screen(TITLE, LINES[top:top + h - 4], status="up/down scroll   Esc leave")
