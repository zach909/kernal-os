#!/usr/bin/env python3
"""Build the productivity suite.

    python3 suite/gen.py list                 every product, its scope, its app name
    python3 suite/gen.py build OUTDIR         write + pack one .kapp per buildable product
    python3 suite/gen.py catalog              rewrite docs/CATALOG.md

Each app is a manifest plus a three-line launcher; all the code lives in
kos/office, which is on every app's import path (like kos.sdk)."""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from kos.kapp import pack  # noqa: E402
from kos.office.catalog import CATALOG  # noqa: E402
from kos.office.packs import entries as pack_entries  # noqa: E402


def every():
    """The 149 core products, then the pack products, then the OS's own apps (the converted commands)."""
    from kos.office.pack_system import ENTRIES as system
    for e in system:
        e.pack = "pack_system"
    return list(CATALOG) + pack_entries() + list(system)


from kos.sysapps import LAUNCHER, manifest  # noqa: E402  (one way to build an app, shared with `kos desktop install`)


def build(out: Path) -> list:
    out.mkdir(parents=True, exist_ok=True)
    made = []
    for e in every():
        if e.scope == "none":
            continue
        with tempfile.TemporaryDirectory() as td:
            d = Path(td) / e.name
            d.mkdir()
            (d / "manifest.json").write_text(json.dumps(manifest(e), indent=2))
            (d / "app.py").write_text(LAUNCHER.format(name=e.name, pack=(f', {e.pack!r}' if getattr(e, 'pack', '') else '')))
            pack(d, out / f"{e.name}.kapp")
        made.append(e.name)
    return made


def catalog_md() -> str:
    lines = ["# Productivity suite catalogue", "",
             "Generated by `python3 suite/gen.py catalog`. Do not edit by hand.", "",
             "Every product you asked for is listed. **Scope** says plainly what it is:", "",
             "* **full**: does the job it is named for, as a single-user local app.",
             "* **partial**: does a real, useful part of it; the note says what is and is not there.",
             "* **none**: not built, with the reason.", "",
             "All apps are single-user and local. KOS apps cannot talk to other apps, other machines, the screen, "
             "audio devices or the network unless the owner grants access, so nothing here syncs, shares live, or "
             "reaches other services on its own.", ""]
    counts = {"full": 0, "partial": 0, "none": 0}
    for e in CATALOG:
        counts[e.scope] += 1
    lines += [f"**{len(CATALOG)} products: {counts['full']} full, {counts['partial']} partial, {counts['none']} not built.**", "",
              "Shared folders: an app that **owns** one creates it (and its permission); an app that **uses** one can look "
             "for it, but is only let in after you run `kos grant APP space:NAME --level read|write`.", "",
             "| Product | App | Scope | Shared folders | What it is / what it is not |", "|---|---|---|---|---|"]
    for e in CATALOG:
        app = f"`{e.name}`" if e.scope != "none" else "-"
        net = " (network)" if e.network else ""
        sh = ", ".join([f"owns `{x}`" for x in e.owns] + [f"uses `{x}`" for x in e.uses]) or "-"
        lines.append(f"| {e.title} | {app}{net} | {e.scope} | {sh} | {e.note.replace('|', '/') or '-'} |")
    packs = pack_entries()
    pc = {"full": 0, "partial": 0, "none": 0}
    for e in packs:
        pc[e.scope] += 1
    lines += ["", "## Extra products (packs)", "",
              "Built after the first 149, from the capability lists in docs/REQUESTED2.txt. Every app here also has the built-in agent (Ctrl-N). "
              "`docs/CAPABILITIES.md` maps every capability that was asked for to the app, OS command or reason that covers it.", "",
              f"**{len(packs)} products: {pc['full']} full, {pc['partial']} partial, {pc['none']} not built.**", "",
              "| Product | App | Scope | What it is / what it is not |", "|---|---|---|---|"]
    for e in packs:
        app = f"`{e.name}`" if e.scope != "none" else "-"
        lines.append(f"| {e.title} | {app}{' (network)' if e.network else ''} | {e.scope} | {e.note.replace('|', '/') or '-'} |")
    from kos import sysapps
    from kos.launchmap import APP_FOR_COMMAND, BOOTSTRAP
    own = sysapps.entries()
    lines += ["", "## The OS's own apps", "",
              "The OS's own commands, as apps (`kos/office/pack_system.py`, and five titles in `pack_os`). Each asks the OS for what it "
              "shows or changes through the service layer (`kos/servicespec.py`); the permission it asks for is in the third column, "
              "and the password is typed in the OS's own prompt every time. `kos desktop install` installs them together.", "",
              f"**{len(own)} apps.** The commands that now open them: `kos/launchmap.py`.", "",
              "| App | Title | Asks the OS for | Opens for these commands | What it is / what it is not |", "|---|---|---|---|---|"]
    for e in own:
        cmds = ", ".join(f"`{c}`" for c, a in {**APP_FOR_COMMAND, **BOOTSTRAP}.items() if a == e.name) or "-"
        asks = ", ".join(f"`service:{g}`" for g in e.services) + (" + `system`" if getattr(e, "system", False) else "")
        lines.append(f"| `{e.name}` | {e.title} | {asks or '-'} | {cmds} | {e.note.replace('|', '/')} |")
    return "\n".join(lines) + "\n"


def main(argv: list) -> int:
    cmd = argv[1] if len(argv) > 1 else "list"
    if cmd == "list":
        for e in every():
            print(f"{e.scope:<8} {e.name if e.scope != 'none' else '-':<36} {e.title}")
        return 0
    if cmd == "build" and len(argv) > 2:
        made = build(Path(argv[2]))
        print(f"packed {len(made)} apps into {argv[2]}")
        return 0
    if cmd == "catalog":
        (ROOT / "docs" / "CATALOG.md").write_text(catalog_md())
        print("wrote docs/CATALOG.md")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
