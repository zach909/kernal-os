def outputs():
    files = {}
    for e in D.E:
        code, man = build(e)
        files[OUT / e["id"] / "app.py"] = code
        files[OUT / e["id"] / "manifest.json"] = man
    files[OUT / "README.md"] = readme()
    return files


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    files = outputs()
    if cmd == "write":
        for p, text in files.items():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
        print(f"wrote {len(D.E)} apps and the README under {OUT}")
    elif cmd == "check":
        bad = [p for p, t in files.items() if not p.is_file() or p.read_text() != t]
        print("apps/store is up to date" if not bad else "out of date: " + ", ".join(str(p) for p in bad[:5]))
        sys.exit(1 if bad else 0)
    else:
        print(__doc__)
        sys.exit(2)


