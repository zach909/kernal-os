from kos.sdk import App

TITLE = "Calculator"
MAX_LEN = 80
MAX_DIGITS = 30
KEEP = 10


def norm(n, d):
    if d == 0:
        raise ValueError("cannot divide by zero")
    g = gcd(n, d)
    n, d = n // g, d // g
    return (-n, -d) if d < 0 else (n, d)


def show(r):
    return str(r[0]) if r[1] == 1 else f"{r[0]}/{r[1]}"


def tokens(text):
    out, i = [], 0
    while i < len(text):
        c = text[i]
        if c == " ":
            i += 1
        elif c in "0123456789":
            j = i
            while j < len(text) and text[j] in "0123456789":
                j += 1
            if j - i > MAX_DIGITS:
                raise ValueError("number too long")
            out.append(("n", int(text[i:j])))
            i = j
        elif c in "+-*/()":
            out.append((c, 0))
            i += 1
        else:
            raise ValueError("cannot use " + ascii(c))
    return out


def evaluate(text):
    """Exact value of an expression as (numerator, denominator). Raises ValueError with a short reason."""
    if len(text) > MAX_LEN:
        raise ValueError("too long")
    toks = tokens(text)
    if not toks:
        raise ValueError("nothing to work out")
    pos = [0]

    def peek():
        return toks[pos[0]][0] if pos[0] < len(toks) else ""

    def take():
        if pos[0] >= len(toks):
            raise ValueError("the sum ends too soon")
        pos[0] += 1
        return toks[pos[0] - 1]

    def factor():
        t = take()
        if t[0] == "n":
            return (t[1], 1)
        if t[0] == "-":
            v = factor()
            return (-v[0], v[1])
        if t[0] == "(":
            v = expr()
            if take()[0] != ")":
                raise ValueError("missing )")
            return v
        raise ValueError("unexpected " + t[0])

    def term():
        v = factor()
        while peek() in ("*", "/"):
            op, w = take()[0], factor()
            v = norm(v[0] * w[0], v[1] * w[1]) if op == "*" else norm(v[0] * w[1], v[1] * w[0])
        return v

    def expr():
        v = term()
        while peek() in ("+", "-"):
            op, w = take()[0], term()
            v = norm(v[0] * w[1] + (w[0] * v[1] if op == "+" else -w[0] * v[1]), v[1] * w[1])
        return v

    v = expr()
    if pos[0] != len(toks):
        raise ValueError("unexpected " + toks[pos[0]][0])
    return v


def lines(state):
    out = ["", "  Exact calculator: + - * / ( )   answers are fractions, never decimals", ""]
    out += ["  " + h for h in state["history"][-KEEP:]]
    out += ["", "  > " + state["text"] + "_", ""]
    if state["note"]:
        out.append("  " + state["note"])
    out.append("  enter works it out   c clears   Esc leaves")
    return out


def main():
    app = App()
    state = {"text": "", "history": [], "note": ""}
