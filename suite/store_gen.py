def scope(e):
    return "shell" if e["arch"] == "info" else "partial"


def devices(e):
    return ", ".join(D.DEVICES[d] for d in e["dev"])


def info_lines(e):
    w = lambda s, ind="  ": textwrap.wrap(s, 70, initial_indent=ind, subsequent_indent=ind)  # noqa: E731
    out = [""] + w("This app is a screen only. It does not do its job yet, and it does not pretend to.")
    out += [""] + w("For: " + e["does"]) + [""] + w("Needs " + D.NEEDS[e["needs"]] + ".")
    if e["note"]:
        out += [""] + w(e["note"])
    if e["see"]:
        out += [""] + w("Instead, in KOS: " + e["see"] + ".")
    out += [""] + w("Ships on: " + devices(e) + ".")
    return out


def build(e):
    body = BODIES[e["arch"]]
    if e["arch"] == "info":
        body = body.replace("@TITLE_R@", repr(e["title"])).replace("@LINES_R@", repr(info_lines(e)))
    elif e["arch"] == "catalog":
        apps = [(x["id"], x["title"], scope(x), devices(x), x["does"], x["note"]) for x in D.E]
        body = body.replace("@APPS_R@", "(\n    " + ",\n    ".join(repr(a) for a in apps) + ",\n)")
    body = (body.replace("@TITLE@", e["title"]).replace("@PREFIX@", PREFIX.get(e["id"], "n"))
            .replace("@DATED@", "True" if e["id"] == "journal" else "False")
            .replace("@CIVIL@", CIVIL).replace("@COMMON@", COMMON).replace("@LISTED@", LISTED))
    # the listed skeleton refers to PREFIX, which only the apps that have it define
    code = HEAD.replace("@ID@", e["id"]).replace("@TITLE@", e["title"]).replace("@DOES@", e["does"]) + body
    manifest = {"name": "store." + e["id"], "version": "1.0", "runtime": "python", "entry": "app:main",
                "modes": ["tui"], "permissions": PERMS.get(e["arch"], []),
                "description": (e["does"] + " " + (e["note"] or "")).strip()[:200]}
    return code, json.dumps(manifest, indent=2) + "\n"


